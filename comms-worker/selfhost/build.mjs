#!/usr/bin/env node
// Builds the relay for workerd: bundles src/ with wrangler (the same bundle
// `wrangler deploy` uploads) and writes a workerd config next to it.
//
//   node selfhost/build.mjs [--out DIR] [--state DIR] [--listen ADDR] [--cron-listen ADDR] [--allow-loopback]
//
// --out          where the bundle and relay.capnp go (default selfhost/build)
// --state        where Durable Object storage lives (default /var/lib/clairix-relay)
// --listen       the relay's HTTP socket (default 127.0.0.1:8787); keep it on
//                loopback: Caddy and the onion service sit in front
// --cron-listen  the socket the cron timer calls (default 127.0.0.1:8789)
// --allow-loopback  let the relay fetch loopback and private addresses. Only
//                for relays run side by side on one machine (the emulator
//                tests): a deployed relay reaches public addresses only, so
//                nothing that talks it into fetching a URL (a relay address,
//                a push endpoint) can reach this machine's own services.
//
// Every setting and secret is read from the environment when workerd starts
// (systemd's EnvironmentFile), so nothing secret is written here.
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}
const out = resolve(arg("--out", join(here, "build")));
const state = resolve(arg("--state", "/var/lib/clairix-relay"));
const listen = arg("--listen", "127.0.0.1:8787");
const cronListen = arg("--cron-listen", "127.0.0.1:8789");
const allowLoopback = process.argv.includes("--allow-loopback");

// The settings the Worker reads (src/env.ts), each bound from the environment
// of the same name. One unset is simply absent, as on Cloudflare.
export const SETTINGS = [
  "ENROLL_SECRET", "TURN_KEY_ID", "TURN_KEY_API_TOKEN", "COIN_INITIAL_BALANCE", "ADMIN_SECRET",
  "WZDX_FEEDS", "HERE_API_KEY", "TOMTOM_API_KEY", "HERE_DAILY_CAP", "TOMTOM_DAILY_CAP", "PUSH_HOSTS",
  "RELAY_ALTERNATES", "MIX_MAX_MS", "RELAY_KEY", "TOKEN_KEY", "RELAY_ORIGIN", "FEDERATION",
];

// Read from wrangler.toml so the two never drift apart.
const toml = readFileSync(join(root, "wrangler.toml"), "utf8");
const compatibilityDate = /^compatibility_date\s*=\s*"([^"]+)"/m.exec(toml)?.[1];
const compatibilityFlags = [...(/^compatibility_flags\s*=\s*\[([^\]]*)\]/m.exec(toml)?.[1] ?? "").matchAll(/"([^"]+)"/g)].map((m) => m[1]);
const namespaces = [...toml.matchAll(/^\[\[durable_objects\.bindings\]\]\s*\nname\s*=\s*"([^"]+)"\s*\nclass_name\s*=\s*"([^"]+)"/gm)]
  .map((m) => ({ binding: m[1], className: m[2] }));
if (!compatibilityDate || namespaces.length === 0) throw new Error("could not read wrangler.toml");

const dist = join(out, "dist");
rmSync(out, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
execFileSync(join(root, "node_modules", ".bin", "wrangler"), ["deploy", "--dry-run", "--outdir", dist], { cwd: root, stdio: "inherit" });
copyFileSync(join(here, "cron.js"), join(out, "cron.js"));

const modules = readdirSync(dist).filter((f) => f.endsWith(".js") || f.endsWith(".wasm")).sort((a, b) => (a === "index.js" ? -1 : b === "index.js" ? 1 : a.localeCompare(b)));
if (modules[0] !== "index.js") throw new Error("no index.js in the bundle");
const str = (s) => JSON.stringify(s);
const moduleLines = modules.map((f) => f.endsWith(".wasm")
  ? `    (name = ${str(f)}, wasm = embed ${str("dist/" + f)}),`
  : `    (name = ${str(f)}, esModule = embed ${str("dist/" + f)}),`);

const config = `# Generated by selfhost/build.mjs: edit that, not this.
using Workerd = import "/workerd/workerd.capnp";

const config :Workerd.Config = (
  services = [
    (name = "relay", worker = .relay),
    (name = "cron", worker = .cron),
    (name = "storage", disk = (path = ${str(state)}, writable = true)),
    (name = "internet", network = (allow = [${allowLoopback ? '"public", "local", "private"' : '"public"'}], tlsOptions = (trustBrowserCas = true))),
  ],
  sockets = [
    (name = "http", address = ${str(listen)}, http = (), service = "relay"),
    (name = "cron", address = ${str(cronListen)}, http = (), service = "cron"),
  ],
);

const relay :Workerd.Worker = (
  modules = [
${moduleLines.join("\n")}
  ],
  compatibilityDate = ${str(compatibilityDate)},
  compatibilityFlags = [${compatibilityFlags.map(str).join(", ")}],
  bindings = [
${namespaces.map((n) => `    (name = ${str(n.binding)}, durableObjectNamespace = ${str(n.className)}),`).join("\n")}
${SETTINGS.map((s) => `    (name = ${str(s)}, fromEnvironment = ${str(s)}),`).join("\n")}
  ],
  durableObjectNamespaces = [
${namespaces.map((n) => `    (className = ${str(n.className)}, uniqueKey = ${str("clairix-relay-" + n.className)}, enableSql = true),`).join("\n")}
  ],
  durableObjectStorage = (localDisk = "storage"),
  globalOutbound = "internet",
);

const cron :Workerd.Worker = (
  modules = [(name = "cron.js", esModule = embed "cron.js")],
  compatibilityDate = ${str(compatibilityDate)},
  compatibilityFlags = ["service_binding_extra_handlers"],
  bindings = [(name = "RELAY", service = "relay")],
);
`;
writeFileSync(join(out, "relay.capnp"), config);
console.log(`Wrote ${join(out, "relay.capnp")} (storage in ${state}, relay on ${listen}, cron on ${cronListen})`);
